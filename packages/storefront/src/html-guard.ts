/**
 * Render storefront rich markup only after applying a DOM allowlist.
 * The parsed document stays inert until tags, attributes and URL contexts are checked.
 */
import { safeImageUrl, safeProductUrl } from "./assistant/url-security.js";

const TAGS = new Set([
  "a", "article", "br", "button", "circle", "div", "fieldset", "figcaption", "figure",
  "h2", "h3", "h4", "header", "i", "img", "input", "label", "legend", "li", "ol",
  "p", "path", "rect", "section", "small", "span", "strong", "svg", "textarea", "ul",
]);
const ATTRIBUTES = new Set([
  "accept", "alt", "autocomplete", "capture", "checked", "class", "cx", "cy", "d",
  "decoding", "disabled", "download", "fill", "for", "height", "hidden", "href", "id",
  "inputmode", "loading", "maxlength", "name", "opacity", "placeholder", "r", "readonly",
  "rel", "required", "role", "rows", "rx", "src", "stroke", "stroke-linecap",
  "stroke-linejoin", "stroke-width", "style", "target", "title", "type", "value",
  "viewbox", "width", "x", "y",
]);
const STYLES = new Set([
  "background", "background-color", "color", "width", "height", "min-width", "max-width",
  "min-height", "max-height", "border-radius", "flex-shrink", "flex-basis", "flex", "object-fit",
]);
const SAFE_STYLE_VALUE = /^(?:#[a-f0-9]{3,8}|(?:0|1|(?:\d+(?:\.\d+)?)(?:px|rem|%|em))|auto|none|transparent|currentcolor|[a-z-]{2,24}|rgba?\([\d., %]+\))$/i;
const CONTROLS = /[\x00-\x20\x7f\\]/;

function safeStyle(value: string): string | null {
  const cleaned: string[] = [];
  for (const declaration of value.split(";")) {
    if (!declaration.trim()) continue;
    const separator = declaration.indexOf(":");
    if (separator < 0) return null;
    const property = declaration.slice(0, separator).trim().toLowerCase();
    const cssValue = declaration.slice(separator + 1).trim();
    const flexRoomChip = property === "flex" && /^0 0 \d{1,3}px$/.test(cssValue);
    if (!STYLES.has(property) || (!SAFE_STYLE_VALUE.test(cssValue) && !flexRoomChip)) return null;
    cleaned.push(`${property}:${cssValue}`);
  }
  return cleaned.length ? cleaned.join(";") : null;
}

function safeHref(value: string, element: Element): boolean {
  if (safeProductUrl(value) === value || value === "/policies/privacy-policy") return true;
  // Local preview downloads are blobs, never arbitrary navigational links.
  return value.startsWith("blob:") && !CONTROLS.test(value) && element.hasAttribute("download");
}

function safeSrc(value: string): boolean {
  // Preview and uploaded-room photos are local object URLs generated by the app.
  return !!safeImageUrl(value) || (value.startsWith("blob:") && !CONTROLS.test(value));
}

function sanitize(node: Node): void {
  if (node.nodeType === 8) { node.parentNode?.removeChild(node); return; }
  if (node.nodeType === 1) {
    const element = node as Element;
    const tag = element.localName.toLowerCase();
    if (!TAGS.has(tag)) { element.parentNode?.removeChild(element); return; }
    for (const attribute of [...element.attributes]) {
      const name = attribute.name.toLowerCase();
      const value = attribute.value;
      if (!(ATTRIBUTES.has(name) || /^aria-[a-z0-9_-]+$/.test(name) || /^data-[a-z0-9_-]+$/.test(name))) {
        element.removeAttribute(attribute.name);
        continue;
      }
      if (name === "href" && (tag !== "a" || !safeHref(value, element))) element.removeAttribute(attribute.name);
      else if (name === "src" && (tag !== "img" || !safeSrc(value))) element.removeAttribute(attribute.name);
      else if (name === "style") {
        const css = safeStyle(value);
        if (css) element.setAttribute("style", css);
        else element.removeAttribute(attribute.name);
      } else if (name === "target" && value !== "_blank") element.removeAttribute(attribute.name);
    }
    if (tag === "a" && element.getAttribute("target") === "_blank") element.setAttribute("rel", "noopener noreferrer");
  }
  for (const child of [...node.childNodes]) sanitize(child);
}

function safeFragment(html: string, owner: Document): DocumentFragment {
  const parsed = new DOMParser().parseFromString(html, "text/html");
  for (const node of [...parsed.body.childNodes]) sanitize(node);
  const fragment = owner.createDocumentFragment();
  for (const node of [...parsed.body.childNodes]) fragment.appendChild(owner.importNode(node, true));
  return fragment;
}

export function setSafeHtml(target: Element, html: string): void {
  target.replaceChildren(safeFragment(html, target.ownerDocument));
}

export function replaceWithSafeHtml(target: Element, html: string): void {
  target.replaceWith(safeFragment(html, target.ownerDocument));
}
